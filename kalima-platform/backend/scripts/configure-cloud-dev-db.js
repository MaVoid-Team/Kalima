const fs = require("fs");
const path = require("path");
const { execFileSync } = require("child_process");

const SSH_HOST = process.env.KALIMA_VPS_SSH_HOST || "root@kalima-edu.com";
const DEV_BACKEND_CONTAINER = process.env.KALIMA_DEV_BACKEND_CONTAINER || "dev-backend-uxm45gcw7oe2gz8uv67mjpde-175029544977";
const PUBLIC_DB_HOST = process.env.KALIMA_DEV_DB_HOST || "82.29.175.176";
const PUBLIC_DB_PORT = process.env.KALIMA_DEV_DB_PORT || "5467";

const envPath = path.resolve(__dirname, "..", ".env.local");

const ssh = (command) => execFileSync("ssh", ["-o", "BatchMode=yes", SSH_HOST, command], {
  encoding: "utf8",
  stdio: ["ignore", "pipe", "pipe"],
}).trim();

const readContainerEnv = (name) => ssh(`docker exec ${DEV_BACKEND_CONTAINER} printenv ${name} || true`);

const quoteEnv = (value) => JSON.stringify(value || "");

function main() {
  const sourceDatabaseUrl = readContainerEnv("DATABASE_URL");
  if (!sourceDatabaseUrl) {
    throw new Error("Could not read DATABASE_URL from the Coolify dev backend container.");
  }

  const databaseUrl = new URL(sourceDatabaseUrl);
  databaseUrl.hostname = PUBLIC_DB_HOST;
  databaseUrl.port = PUBLIC_DB_PORT;

  const contents = [
    "# Local-only development config. This file is gitignored.",
    "# Generated by: npm run db:dev:configure",
    `DATABASE_URL=${quoteEnv(databaseUrl.toString())}`,
    "PORT=5001",
    "NODE_ENV=development",
    "FIREBASE_AUTH_LOCAL_DEV_BYPASS=true",
    "JWT_SECRET=local-dev-secret",
    "ACCESS_TOKEN_SECRET=local-dev-access-secret",
    "REFRESH_TOKEN_SECRET=local-dev-refresh-secret",
    "APP_URL=http://localhost:5173",
    "",
  ].join("\n");

  fs.writeFileSync(envPath, contents, { mode: 0o600 });
  console.log(`Wrote ${path.relative(process.cwd(), envPath)} for the shared cloud dev database.`);
  console.log("No SSH tunnel is required for normal local development.");
}

main();
